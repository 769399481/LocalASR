"""Read-only packaging path check; run in Conda asr. No builds or cleanup."""
import ast
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    if Path(sys.prefix).name.lower() != "asr":
        raise SystemExit("Run in Conda asr")
    required = ["build.ps1", "distribution/build.py", "distribution/build_support.py",
                "distribution/LocalASR.spec", "distribution/runtime_hook.py",
                "distribution/hooks", "distribution/notices.py", "THIRD_PARTY_NOTICES.md",
                "src/desktop_entry.py", "src/model_catalog.json", "src/app_version.py",
                "src/ui_theme.py", "src/ui_shapes.py"]
    missing = [name for name in required if not (ROOT / name).exists()]
    if missing:
        raise SystemExit("Missing: " + ", ".join(missing))
    for name in required:
        if name.endswith((".py", ".spec")):
            ast.parse((ROOT / name).read_text(encoding="utf-8-sig"), filename=name)
    json.loads((ROOT / "src/model_catalog.json").read_text(encoding="utf-8"))
    sys.path.insert(0, str(ROOT / "src"))
    from app_version import APP_VERSION
    print(json.dumps({"passed": True, "version": APP_VERSION, "checked": required,
                      "icon": "No custom external icon configured",
                      "ui_assets": "Generated by Tk; tkinterdnd2 collected by spec",
                      "scope": "Static paths and syntax only; not a build or runtime verification"}, indent=2))


if __name__ == "__main__":
    main()
